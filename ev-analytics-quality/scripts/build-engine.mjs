// Joins the engine parts into one server module. Runs before dev and build.
import {readdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=join(dirname(fileURLToPath(import.meta.url)),'../src/server/workspace');
const parts=readdirSync(join(dir,'parts')).filter(f=>f.endsWith('.js')).sort();
const body=parts.map(f=>`\n/* ---- ${f} ---- */\n`+readFileSync(join(dir,'parts',f),'utf8')).join('\n');
writeFileSync(join(dir,'engine.js'),`/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/build-engine.mjs from ./parts. Edit the parts, not this file.\nconst engine=(function(){\n${body}\nreturn {query,navFor,roleList,assistantContext,assistantLocal,NATIVE,endpoints:Object.keys(Q)};\n})();\nmodule.exports=engine;\n`);
console.log('engine.js built from',parts.length,'parts');
